int main(int argc,char **argv) {
    try {
        if(argc!=3)throw std::runtime_error("usage: native540-compile-transform INPUT.comp NEW_OUTPUT_DIRECTORY");
        std::ifstream in(argv[1],std::ios::binary|std::ios::ate);
        if(!in)throw std::runtime_error("input unreadable");
        const auto length=in.tellg();
        if(length<=0||length>65536)throw std::runtime_error("GLSL size out of bounds");
        std::string source(static_cast<size_t>(length),'\0');in.seekg(0);in.read(source.data(),length);
        if(!in||source!=sourceText)throw std::runtime_error("only exact pinned GLSL430 dual-SSBO global-ID transform admitted; no rewriting");
        auto image=std::make_unique<QGPUProgramImage>();image->version=GPU::JIT::Version;image->gpu=540;
        std::strcpy(image->name,"Transform540");char diagnostic[4096]{};
        if(!qgpu_compile_glsl(source.c_str(),0,image.get(),diagnostic,sizeof(diagnostic)))
            throw std::runtime_error(diagnostic[0]?diagnostic:"GLSL compiler failed");
        const auto raw=image->info;
        // Exact-source declarations are supplied as upstream compileEntries at
        // lines53/68-70/77. Bare backend has no source reflection. Preserve raw
        // and reject a changed contract rather than overwriting populated fields.
        if(raw.bufferMask||raw.writeMask||raw.varyingCount)throw std::runtime_error("bare backend reflection contract changed");
        for(auto stride:raw.strides)if(stride)throw std::runtime_error("bare backend stride contract changed");
        image->info.bufferMask=3;image->info.writeMask=2;image->info.strides[0]=4;image->info.strides[1]=4;
        for(auto &v:image->info.varyings)v={};
        if(!GPU::JIT::valid(*image,0))throw std::runtime_error("actual transform rejected by QGPUJIT::valid");
        if(image->info.stage||image->info.groupID==252||image->info.bufferMask!=3||image->info.writeMask!=2)
            throw std::runtime_error("not global-ID dual SSBO read0/write1 compute");
        const std::filesystem::path dir(argv[2]);
        if(!std::filesystem::create_directory(dir))throw std::runtime_error("refusing to replace evidence");
        blob(dir/"transform.comp",source.data(),source.size());blob(dir/"transform.ir3",image->code,image->info.codeWords*4);
        blob(dir/"backend-reflection.bin",&raw,sizeof(raw));blob(dir/"final-reflection.bin",&image->info,sizeof(image->info));
        blob(dir/"transform.jit",image.get(),sizeof(*image));
        std::ofstream h(dir/"transform_fixture.h");header(h,*image);h.close();if(!h)throw std::runtime_error("header write failure");
        std::ofstream m(dir/"manifest.json");
        m<<"{\"schema\":1,\"gpu\":540,\"jitVersion\":"<<GPU::JIT::Version
         <<",\"producer\":\"qgpu_compile_glsl\",\"route\":\"GLSL-NIR-A540-IR3\",\"entry\":\"Transform540\","
           "\"jitValid\":true,\"metalCompiler\":false,\"runtimeVerified\":false,\"compiledGLSLVersion\":430,"
           "\"sagit\":\""<<sagit<<"\",\"mesa\":\""<<mesa<<"\",\"input\":{\"shader\":\"transform.comp\",\"sha256\":\""<<sha(source.data(),source.size())
         <<"\"},\"dispatch\":{\"groups\":[4,1,1],\"local\":[64,1,1]},\"outputBytes\":1024,\"inputBytes\":1024,\"guardWords\":768,"
           "\"backendReflectionSHA256\":\""<<sha(&raw,sizeof(raw))<<"\",\"finalReflectionSHA256\":\""<<sha(&image->info,sizeof(image->info))
         <<"\",\"finalJIT\":{\"sha256\":\""<<sha(image.get(),sizeof(*image))<<"\",\"bytes\":"<<sizeof(*image)
         <<"},\"reflectionComposition\":\"exact-source declarations mask3/write2/stride4,4 + zero inactive varyings; sagit Compiler.cpp::compileEntries; no ISA/constants/sysval edits\","
           "\"variants\":[{\"name\":\"base\",\"shader\":\"transform.ir3\",\"sha256\":\""<<sha(image->code,image->info.codeWords*4)<<"\",\"info\":";
        description(m,image->info);m<<",\"immediates\":[";
        for(unsigned i=0;i<image->info.immediateCount;++i){if(i)m<<',';m<<image->immediates[i];}
        m<<"]}],\"backendReflection\":";description(m,raw);m<<"}\n";m.close();if(!m)throw std::runtime_error("manifest write failure");
        std::cout<<"QGPUJIT valid actual A540 transform codeWords="<<image->info.codeWords<<" instrlen="<<image->info.instrlen
         <<" constlen="<<image->info.constlen<<" full="<<image->info.fullRegs<<" half="<<image->info.halfRegs
         <<" localID="<<image->info.localID<<" groupID="<<image->info.groupID<<" flags="<<image->info.flags<<'\n';
        return 0;
    }catch(const std::exception &e){std::cerr<<e.what()<<'\n';return 1;}
}
