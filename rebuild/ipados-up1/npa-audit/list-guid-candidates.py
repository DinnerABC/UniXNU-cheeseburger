#!/usr/bin/env python3
"""List GUID-shaped constants in the firmware drivers that matter for RPM/NPA.

Read-only offline analysis: no device access, no build. A GUID is taken as
Data1..Data3 little endian plus eight raw bytes; the candidate filter only keeps
values whose Data4[0] carries the RFC 4122 variant (0x80..0xbf), which is what
edk2 GUIDs use in practice.
"""
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
AUDIT = ROOT / 'out/p21/npa-audit'
FILES = ['NpaDxe.efi', 'GlinkDxe.efi', 'PmicDxe.efi', 'SPMI.efi']

# depex expressions reference the protocols a driver waits for; those GUIDs are
# useful to recognise the SPMI/PMIC interfaces even though we cannot read the
# autogenerated INF protocol lists.
SERVER = Path(sys.argv[1]) if len(sys.argv) > 1 else None


def guids(data: bytes):
    out = {}
    for off in range(0, len(data) - 16, 4):
        b = data[off:off + 16]
        if not (0x80 <= b[8] <= 0xbf):
            continue
        d1 = struct.unpack_from('<I', b, 0)[0]
        d2, d3 = struct.unpack_from('<HH', b, 4)
        # Reject obvious code/strings: the first three fields must not all be
        # tiny or look like ASCII runs.
        if d1 < 0x1000 or d2 == 0 or d3 == 0:
            continue
        key = (d1, d2, d3) + tuple(b[8:16])
        out.setdefault(key, []).append(off)
    return out


def fmt(k):
    d1, d2, d3, *rest = k
    return '%08X-%04X-%04X-%02X%02X-%02X%02X%02X%02X%02X%02X' % (
        d1, d2, d3, rest[0], rest[1], rest[2], rest[3], rest[4], rest[5], rest[6], rest[7])


def depex_guids(data: bytes):
    out = {}
    i = 0
    while i < len(data):
        op = data[i]
        if op == 0x02:            # PUSH
            if i + 17 <= len(data):
                b = data[i + 1:i + 17]
                out[fmt(struct.unpack('<IHH8B', b))] = i
            i += 17
        else:
            i += 1
    return out


def main():
    seen = {}
    for name in FILES:
        p = AUDIT / name
        if not p.is_file():
            print(f'{name}: missing')
            continue
        table = guids(p.read_bytes())
        print(f'{name}: {len(table)} candidate GUIDs')
        for k, offs in table.items():
            seen.setdefault(fmt(k), []).append(name)
    print('\nGUIDs present in more than one driver (likely shared protocols):')
    for g, names in sorted(seen.items()):
        if len(set(names)) > 1:
            print(' ', g, sorted(set(names)))
    if SERVER:
        print('\ndepex GUIDs:')
        for name in ['PmicDxe', 'NpaDxe']:
            p = SERVER / name / f'{name}.depex'
            if p.is_file():
                print(' ', name, depex_guids(p.read_bytes()))
    out = ROOT / 'out/p21/npa-audit/guid-candidates.txt'
    with out.open('w') as f:
        for g, names in sorted(seen.items()):
            f.write(f'{g} {",".join(sorted(set(names)))}\n')
    print('\nwritten', out)


if __name__ == '__main__':
    main()
